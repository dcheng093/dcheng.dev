// Post-build: writes dist/_redirects so all-lowercase URLs reach files whose real names use capitals
// (e.g. /me/misc-01.jpg serves /me/MISC-01.JPG). The deployed asset server is case-sensitive; the
// Windows-backed dev folder is not, so a lowercase copy of each file can't be made on disk instead.
// Rules are 200 rewrites (not redirects), so the address stays as typed and nothing can loop.
import { readdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const dist = resolve(import.meta.dirname, '../dist')
const rules = []
for (const dir of ['me', 'gifs']) {
  for (const name of (await readdir(resolve(dist, dir))).sort()) {
    // README.txt is kept off the site by public/.assetsignore, so it gets no alias either.
    if (name !== name.toLowerCase() && name !== 'README.txt') rules.push(`/${dir}/${name.toLowerCase()} /${dir}/${name} 200`)
  }
}
await writeFile(resolve(dist, '_redirects'), `# Generated by scripts/case-aliases.mjs\n${rules.join('\n')}\n`)
console.log(`_redirects: ${rules.length} lowercase aliases`)
