// npm run gifs:webp: re-encodes the site's GIFs (public/gifs/) as lossless animated WebP wherever that's smaller.
// Every pixel, frame and delay is kept, so nothing looks different; the GIF goes to asset-originals/gifs/.
// Run it after `npm run gifs:adopt` (which adopts new GIFs as .gif, so flicker.mjs can check them first).
// It keeps as GIF:
//   - anything WebP doesn't shrink;
//   - cursors (cur-*, and ic-flame, Home's last band): CSS cursors want the format every browser takes;
//   - GIFs with frames of 10 ms or less: browsers slow those GIF frames to ~100 ms but play WebP frames as written,
//     so they'd run faster.
// Then it writes src/content/webpGifs.ts (which ids are WebP now; `gif()` in assets.ts reads it) and points every
// other reference at the new file: the tile url()s in src/index.css, src/three/pageScenes.ts, and the credits.
import { existsSync } from 'node:fs'
import { copyFile, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import sharp from 'sharp'

const root = resolve(import.meta.dirname, '../..')
const dir = resolve(root, 'public/gifs')
const originals = resolve(root, 'asset-originals/gifs')
const CURSORS = /^cur-|^ic-flame$/
await mkdir(originals, { recursive: true })

const converted = []
let saved = 0
for (const file of (await readdir(dir)).filter((f) => f.endsWith('.gif')).sort()) {
  const id = file.slice(0, -4)
  if (CURSORS.test(id)) continue
  const here = resolve(dir, file)
  const meta = await sharp(here, { animated: true }).metadata()
  if ((meta.delay ?? []).some((d) => d <= 10)) continue
  // A loop count past WebP's limit (one GIF says 65536) is "forever" in practice either way.
  const timing = (meta.pages ?? 1) > 1 ? { delay: meta.delay, loop: Math.min(meta.loop ?? 0, 65535) } : {}
  const webp = await sharp(here, { animated: true }).webp({ lossless: true, effort: 6, ...timing }).toBuffer()
  const before = (await stat(here)).size
  if (webp.length >= before) continue
  if (!existsSync(resolve(originals, file))) await copyFile(here, resolve(originals, file))
  await writeFile(resolve(dir, `${id}.webp`), webp)
  await rm(here)
  saved += before - webp.length
  converted.push(id)
}
// Earlier runs' conversions count too (their GIFs are already gone).
const all = (await readdir(dir)).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5)).sort()

await writeFile(
  resolve(root, 'src/content/webpGifs.ts'),
  `// Generated by scripts/photos/gifs-to-webp.mjs (npm run gifs:webp): the GIFs in public/gifs/ that are lossless WebP
// now (same pixels, frames and delays, fewer bytes). \`gif()\` in assets.ts picks the extension from this.
export const WEBP_GIFS: ReadonlySet<string> = new Set(${JSON.stringify(all, null, 2).replace(/"/g, "'")})\n`,
)

// Every other place a GIF is named by its path or file name.
const targets = ['src/index.css', 'src/three/pageScenes.ts', 'public/gifs/CREDITS.md'].map((f) => resolve(root, f))
for (const f of targets) {
  const text = await readFile(f, 'utf8')
  let next = text
  for (const id of all) next = next.split(`/gifs/${id}.gif`).join(`/gifs/${id}.webp`).split(`${id}.gif`).join(`${id}.webp`)
  if (next !== text) {
    await writeFile(f, next)
    console.log(`updated ${f.slice(root.length + 1)}`)
  }
}
console.log(`${converted.length} GIFs converted this run (${Math.round(saved / 1024)} KB saved); ${all.length} are WebP in all.`)
