export const GLYPH_W = 5
export const GLYPH_H = 7

/** Lit pixels of a word as [x, y] (y = 0 at the top), with one blank column between letters. */
export function voxelWord(word: string): { pixels: [number, number][]; width: number } {
  const pixels: [number, number][] = []
  const chars = [...word.toUpperCase()]
  chars.forEach((ch, i) => {
    const rows = (GLYPHS[ch] ?? GLYPHS['?']).split('|')
    rows.forEach((row, y) => [...row].forEach((cell, x) => cell === '#' && pixels.push([i * (GLYPH_W + 1) + x, y])))
  })
  return { pixels, width: Math.max(1, chars.length * (GLYPH_W + 1) - 1) }
}

export const hasGlyph = (ch: string) => ch.toUpperCase() in GLYPHS
